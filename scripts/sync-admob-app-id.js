// Writes the AdMob App ID from .env.<mode> into the Android resources the manifest reads
// (android/app/src/main/res/values/admob.xml -> @string/admob_app_id).
// Usage: node scripts/sync-admob-app-id.js android | android.production
// For production it also refuses placeholder or Google test IDs, so a release can't ship test ads.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const mode = process.argv[2] || 'android';
const envFile = path.join(root, `.env.${mode}`);
const KEYS = ['VITE_ADMOB_APP_ID', 'VITE_ADMOB_BANNER_ID', 'VITE_ADMOB_INTERSTITIAL_ID', 'VITE_ADMOB_REWARDED_ID'];
const GOOGLE_TEST_PUBLISHER = 'ca-app-pub-3940256099942544';

function fail(msg) {
  console.error(`[sync-admob] ${msg}`);
  process.exit(1);
}

if (!fs.existsSync(envFile)) fail(`${path.basename(envFile)} not found`);

const env = {};
for (const line of fs.readFileSync(envFile, 'utf8').split(/\r?\n/)) {
  const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
  if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
}

const appId = env.VITE_ADMOB_APP_ID;
if (!appId || !/^ca-app-pub-\d{16}~\d{10}$/.test(appId)) fail(`VITE_ADMOB_APP_ID in ${path.basename(envFile)} is missing or malformed: "${appId ?? ''}"`);

if (mode.endsWith('.production')) {
  for (const k of KEYS) {
    const v = env[k] ?? '';
    if (!/^ca-app-pub-\d{16}[~/]\d{10}$/.test(v)) fail(`${k} is not a real AdMob ID yet: "${v}"`);
    if (v.startsWith(GOOGLE_TEST_PUBLISHER)) fail(`${k} is a Google test ID; use your own for release`);
  }
  if (env.VITE_ADMOB_IS_TESTING !== 'false') fail('VITE_ADMOB_IS_TESTING must be false for release');
}

const resDir = path.join(root, 'android/app/src/main/res/values');
if (!fs.existsSync(resDir)) fail('android/ project missing: run `npx cap add android` first');
const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/sync-admob-app-id.js from .env.${mode}; do not edit by hand. -->
<resources>
    <string name="admob_app_id" translatable="false">${appId}</string>
</resources>
`;
fs.writeFileSync(path.join(resDir, 'admob.xml'), xml);
console.log(`[sync-admob] admob_app_id = ${appId} (from .env.${mode})`);
